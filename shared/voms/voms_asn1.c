/* Decode an extension's OCTET STRING contents as `it`; NULL on any error. */
static void *
voms_ext_decode(X509_EXTENSION *ext, const ASN1_ITEM *it)
{
    const ASN1_OCTET_STRING *data;
    const unsigned char     *p;

    if (ext == NULL) {
        return NULL;
    }
    data = X509_EXTENSION_get_data(ext);
    if (data == NULL) {
        return NULL;
    }
    p = ASN1_STRING_get0_data(data);
    return ASN1_item_d2i(NULL, &p, ASN1_STRING_length(data), it);
}

VOMS_CERTS *
voms_ext_certs(X509_EXTENSION *ext)
{
    return voms_ext_decode(ext, ASN1_ITEM_rptr(VOMS_CERTS));
}

VOMS_FULL_ATTRIBUTES *
voms_ext_attributes(X509_EXTENSION *ext)
{
    return voms_ext_decode(ext, ASN1_ITEM_rptr(VOMS_FULL_ATTRIBUTES));
}

VOMS_TARGETS *
voms_ext_targets(X509_EXTENSION *ext)
{
    return voms_ext_decode(ext, ASN1_ITEM_rptr(VOMS_TARGETS));
}

X509_EXTENSION *
voms_acinfo_extension(const VOMS_AC_INFO *acinfo, const char *oid)
{
    char txt[80];
    int  i, n;

    if (acinfo == NULL || acinfo->extensions == NULL) {
        return NULL;
    }
    n = sk_X509_EXTENSION_num(acinfo->extensions);
    for (i = 0; i < n; i++) {
        X509_EXTENSION *ext = sk_X509_EXTENSION_value(acinfo->extensions, i);

        if (OBJ_obj2txt(txt, sizeof(txt), X509_EXTENSION_get_object(ext), 1) > 0
            && strcmp(txt, oid) == 0)
        {
            return ext;
        }
    }
    return NULL;
}
