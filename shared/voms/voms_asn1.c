/*
 * shared/voms/voms_asn1.c — ASN.1 templates for VOMS attribute certificates
 *
 * WHAT: The OpenSSL template definitions behind voms_asn1.h, generating the
 *       d2i, i2d and free functions used by the decoder and verifier.
 * WHY:  One strict DER grammar for everything the library reads; a malformed
 *       extension fails to decode instead of being scanned heuristically.
 * HOW:  RFC 5755 shapes with IMPLICIT tagging; VOMS_AC_INFO records its
 *       original encoding (ASN1_SEQUENCE_enc) for signature verification.
 */

