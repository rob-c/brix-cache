/* rpm_classify.c — the RPM repository route classifier (phase-104 D15.9).
 *
 * WHAT: parse a decoded request URI into brix_rpm_req_t: which of the four
 *       repository object classes it names, plus the checksum a digest-named
 *       metadata file carries in its own name.
 * WHY:  see rpm_classify.h — one validating parse at the edge is both the
 *       cache policy (what may live forever, what must expire, what certifies
 *       itself) and the whole traversal defense for the paths the mirror
 *       composes out of the key afterwards.
 * HOW:  a single left-to-right walk that validates every component and
 *       remembers the last two slashes. The route needs exactly the final
 *       component and its parent directory, so the walk needs no component
 *       array and has no bound to overflow. The grammar is deliberately
 *       narrower than POSIX allows: an RPM repository is generated by
 *       createrepo out of package NVRAs, and every byte outside that set is a
 *       path this mirror has no reason to be able to name.
 */

#include "rpm_classify.h"

#include <string.h>

/* The bytes a repository path may contain. Alphanumerics plus the punctuation
 * RPM version grammar and repo layouts actually use: `.` `_` `-` `+` (epoch/
 * NVRA), `~` and `^` (RPM's pre-/post-release version markers), `:` `,` `@`
 * `=` (module and appstream directory names). Space, `%`, `?`, `\`, quotes and
 * every non-ASCII byte are refused — a path outside this set is either an
 * encoding accident or a probe, and neither should reach an open(). */
static int
rpm_byte_ok(char c)
{
    if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
        || (c >= '0' && c <= '9'))
    {
        return 1;
    }
    return strchr("._-+~^:,@=", c) != NULL && c != '\0';
}

/* One slash-delimited component. Empty ("//"), "." and ".." are refused
 * outright rather than normalized: the key is served back to the origin and
 * used as a store path, and two spellings of one object are two cache entries
 * of which at most one can be right. */
static int
rpm_component_ok(const char *p, size_t n)
{
    size_t i;

    if (n == 0) {
        return 0;
    }
    if ((n == 1 && p[0] == '.') || (n == 2 && p[0] == '.' && p[1] == '.')) {
        return 0;
    }
    for (i = 0; i < n; i++) {
        if (!rpm_byte_ok(p[i])) {
            return 0;
        }
    }
    return 1;
}

static int
rpm_is_hex(const char *p, size_t n)
{
    size_t i;

    for (i = 0; i < n; i++) {
        if (!((p[i] >= '0' && p[i] <= '9') || (p[i] >= 'a' && p[i] <= 'f')
              || (p[i] >= 'A' && p[i] <= 'F')))
        {
            return 0;
        }
    }
    return n > 0;
}

static int
rpm_ends_with(const char *p, size_t n, const char *suffix)
{
    size_t s = strlen(suffix);

    return n > s && memcmp(p + n - s, suffix, s) == 0;
}

static int
rpm_is(const char *p, size_t n, const char *lit)
{
    size_t s = strlen(lit);

    return n == s && memcmp(p, lit, s) == 0;
}

/* Walk the path, validating each component, and report the last two: the file
 * and the directory holding it. Returns 0, or -1 with *err set. */
static int
rpm_split(const char *uri, size_t len, const char **file, size_t *file_len,
    const char **dir, size_t *dir_len, brix_rpm_err_t *err)
{
    size_t start = 1, i;

    *file = NULL; *file_len = 0;
    *dir  = NULL; *dir_len  = 0;

    if (len == 0 || uri[0] != '/') {
        *err = BRIX_RPM_ERR_PATH_INVALID;
        return -1;
    }
    if (len >= BRIX_RPM_PATH_MAX) {
        *err = BRIX_RPM_ERR_PATH_TOO_LONG;
        return -1;
    }
    if (len == 1 || uri[len - 1] == '/') {
        *err = BRIX_RPM_ERR_NOT_A_FILE;   /* a mirror serves files, not trees */
        return -1;
    }

    for (i = 1; i <= len; i++) {
        if (i < len && uri[i] != '/') {
            continue;
        }
        if (!rpm_component_ok(uri + start, i - start)) {
            *err = BRIX_RPM_ERR_PATH_INVALID;
            return -1;
        }
        *dir = *file; *dir_len = *file_len;      /* the previous one, if any */
        *file = uri + start; *file_len = i - start;
        start = i + 1;
    }

    *err = BRIX_RPM_ERR_NONE;
    return 0;
}

/* repomd.xml and the two files that travel with it. Named exactly, not by
 * prefix: "repomd.xml.bak" left behind by a sync script is not the freshness
 * root and must not be served as one. */
static int
rpm_is_repomd(const char *f, size_t n)
{
    return rpm_is(f, n, "repomd.xml") || rpm_is(f, n, "repomd.xml.asc")
        || rpm_is(f, n, "repomd.xml.key");
}

/* `<hex>-<name>`, the shape createrepo gives every file it writes beside
 * repomd.xml. The hex length must be one an algorithm claims, or the name is
 * not a digest — a package named "deadbeef-tool-1.0.rpm" would otherwise be
 * "verified" against a checksum nobody computed. */
static int
rpm_digest_named(const char *f, size_t n, const char **hex, size_t *hex_len)
{
    const char *dash = memchr(f, '-', n);
    size_t      h;

    if (dash == NULL) {
        return 0;
    }
    h = (size_t) (dash - f);
    if (brix_rpm_alg_for_hexlen(h) == NULL || !rpm_is_hex(f, h)
        || h + 1 >= n)
    {
        return 0;
    }
    *hex = f;
    *hex_len = h;
    return 1;
}

int
brix_rpm_classify(const char *uri, size_t len, brix_rpm_req_t *out)
{
    const char *dir;
    size_t      dir_len;

    memset(out, 0, sizeof(*out));

    if (rpm_split(uri, len, &out->file, &out->file_len, &dir, &dir_len,
                  &out->err) != 0)
    {
        out->cls = BRIX_RPM_REQ_BAD;
        return -1;
    }

    if (dir != NULL && rpm_is(dir, dir_len, "repodata")) {
        if (rpm_is_repomd(out->file, out->file_len)) {
            out->cls = BRIX_RPM_REQ_REPOMD;
        } else if (rpm_digest_named(out->file, out->file_len, &out->hex,
                                    &out->hex_len)) {
            out->cls = BRIX_RPM_REQ_METADATA;
        } else {
            /* A repo generated with --simple-md-filenames: the file carries
             * no checksum, so nothing here can prove it immutable. It gets
             * the mutable window, which is the safe half of the mistake. */
            out->cls = BRIX_RPM_REQ_AUX;
        }
        return 0;
    }

    out->cls = (rpm_ends_with(out->file, out->file_len, ".rpm")
                || rpm_ends_with(out->file, out->file_len, ".drpm"))
               ? BRIX_RPM_REQ_PACKAGE : BRIX_RPM_REQ_AUX;
    return 0;
}

const char *
brix_rpm_alg_for_hexlen(size_t hex_len)
{
    switch (hex_len) {
    case 40:  return "sha1";
    case 64:  return "sha256";
    case 96:  return "sha384";
    case 128: return "sha512";
    default:  return NULL;
    }
}

const char *
brix_rpm_class_str(brix_rpm_class_t cls)
{
    switch (cls) {
    case BRIX_RPM_REQ_REPOMD:   return "repomd";
    case BRIX_RPM_REQ_METADATA: return "metadata";
    case BRIX_RPM_REQ_PACKAGE:  return "package";
    case BRIX_RPM_REQ_AUX:      return "aux";
    default:                    return "bad";
    }
}

int
brix_rpm_class_is_mutable(brix_rpm_class_t cls)
{
    return cls == BRIX_RPM_REQ_REPOMD || cls == BRIX_RPM_REQ_AUX;
}
